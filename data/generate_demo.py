"""Generate synthetic compositions, processes and text for the demo."""

import csv
import json
import random
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "data/demo"
SEED = 20261115
ELEMENTS = ["Ti", "Mo", "Al", "Sn", "V", "Zr", "Cr", "Nb", "Ta", "Fe", "W",
            "Si", "O", "C", "N", "H", "Ni", "Cu", "B", "Mn", "Y", "Zn", "TiB"]
NEUTRAL = "Processing condition not specified for composition-stage screening"


def composition(rng):
    ranges = {"Al": (4.5, 6.5), "V": (2.5, 4.5), "Mo": (0.5, 2.5),
              "Fe": (0.3, 1.5), "Sn": (1.5, 2.8)}
    row = {f"{el} (wt%)": 0.0 for el in ELEMENTS}
    for el, bounds in ranges.items():
        row[f"{el} (wt%)"] = round(rng.uniform(*bounds), 4)
    row["Ti (wt%)"] = round(100.0 - sum(row.values()), 4)
    return row


def toy_properties(row, secondary_temp=800.0, final_deformation=0.0):
    """Generate synthetic UTS and EL targets."""
    mo_eq = row["Mo (wt%)"] + 0.67 * row["V (wt%)"] + 2.9 * row["Fe (wt%)"]
    al_eq = row["Al (wt%)"] + row["Sn (wt%)"] / 3
    uts = 650.0 + 55.0 * mo_eq + 32.0 * al_eq
    uts += 0.2 * (secondary_temp - 800.0) + 1.8 * final_deformation
    el = 29.0 - 0.75 * mo_eq + 0.30 * row["Sn (wt%)"]
    el -= 0.01 * (secondary_temp - 800.0) + 0.02 * final_deformation
    return round(uts, 6), round(el, 6)


def write_csv(path, rows):
    with path.open("w", encoding="utf-8", newline="") as stream:
        writer = csv.DictWriter(stream, fieldnames=list(rows[0]))
        writer.writeheader()
        writer.writerows(rows)


def main():
    DATA.mkdir(parents=True, exist_ok=True)
    rng = random.Random(SEED)
    records = {}
    for stage in ("composition", "processing"):
        rows = []
        for _ in range(24):
            row = composition(rng)
            temp, deformation = 800.0, 0.0
            process = NEUTRAL
            if stage == "processing":
                temp = rng.choice([850.0, 900.0])
                passes = rng.choice([2, 4, 6])
                deformation = rng.choice([60.0, 75.0])
                process = (
                    "Initial Forging: 1100.0°C for 0.5h, 40% deformation. "
                    f"Secondary Forging: {temp:.1f}°C for 2.0min, 5% deformation per pass, "
                    f"passes: {passes}, total cyclic deformation: {passes * 5}%. "
                    f"Final total deformation: {deformation:g}%, cooled by "
                    "Air Cool (AC) for 5s followed by Water Quench (WQ)."
                )
            uts, el = toy_properties(row, temp, deformation)
            row.update({"transition temperature (°C)": 0.0, "Process": process,
                        "Strength (MPa)": uts, "Elongation (%)": el,
                        "source": "SYNTHETIC_TOY_EQUATION_NOT_EXPERIMENTAL"})
            rows.append(row)
        write_csv(DATA / f"{stage}.csv", rows)
        records[stage] = rows
    candidates = [{"candidate_id": f"DEMO-COMP-{i + 1:04d}", **composition(rng)}
                  for i in range(12)]
    write_csv(DATA / "candidates.csv", candidates)
    documents = []
    for i in range(12):
        documents.append(
            f"This is synthetic titanium alloy example {i + 1}.\n"
            "Aluminium and vanadium are composition inputs in this toy example.\n"
            "Molybdenum iron and tin vary across fictional alloy records.\n"
            "Forging temperature and deformation describe a fictional process.\n"
            "Strength and elongation are generated by illustrative equations.\n"
        )
    corpus = "\n".join(documents)
    (DATA / "corpus.txt").write_text(corpus, encoding="utf-8")
    # Build the Demo vocabulary.
    input_records = {stage: [{key: value for key, value in row.items()
                              if key not in {"Strength (MPa)", "Elongation (%)", "source"}}
                             for row in rows] for stage, rows in records.items()}
    text = corpus + json.dumps(input_records, ensure_ascii=False) + json.dumps(candidates)
    text += " Titanium alloy composition Process description Water Quench WQ Air Cool AC "
    words = re.findall(r"[a-z]+|[0-9]+|[^\w\s]", text.lower())
    tokens = ["[PAD]", "[UNK]", "[CLS]", "[SEP]", "[MASK]"]
    tokens += sorted(set(words) | set("abcdefghijklmnopqrstuvwxyz0123456789"))
    tokens += ["##" + char for char in "abcdefghijklmnopqrstuvwxyz0123456789"]
    tokens = list(dict.fromkeys(tokens))
    (DATA / "vocab.txt").write_text("\n".join(tokens) + "\n", encoding="utf-8")
    design = {
        "fixed_process": {"initial_temp": 1100.0, "initial_time": 0.5,
                          "initial_deformation": 40.0, "secondary_time": 2.0,
                          "deformation_per_pass": 5.0,
                          "cooling_type": "Air Cool (AC) for 5s followed by Water Quench (WQ)"},
        "process_space": {"secondary_temp": [850.0, 900.0], "passes": [2, 4, 6],
                          "total_cyclic_deformation": [10.0, 20.0, 30.0],
                          "final_total_deformation": [60.0, 75.0]},
    }
    (ROOT / "configs/design_demo.json").write_text(json.dumps(design, indent=2) + "\n")
    bert = {"attention_probs_dropout_prob": 0.1, "hidden_act": "gelu",
            "hidden_dropout_prob": 0.1, "hidden_size": 32, "initializer_range": 0.02,
            "intermediate_size": 64, "max_position_embeddings": 128,
            "num_attention_heads": 4, "num_hidden_layers": 12,
            "type_vocab_size": 2, "vocab_size": len(tokens)}
    (ROOT / "configs/bert_demo.json").write_text(json.dumps(bert, indent=2) + "\n")
    print("Wrote synthetic CSV data, corpus and vocabulary to data/demo/.")


if __name__ == "__main__":
    main()
